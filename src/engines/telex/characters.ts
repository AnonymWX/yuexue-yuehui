/**
 * 随机抽一个字符（不与上一次重复）
 */
export function pickRandomChar(pool: string[], exclude?: string): string {
  if (pool.length === 0) return ''
  if (pool.length === 1) return pool[0]
  let c = ''
  do {
    c = pool[Math.floor(Math.random() * pool.length)]
  } while (c === exclude)
  return c
}
